"""Writes C definitions, each returning fmi3Error, for every FMI 3.0 entry point that
dc_drive.c does not implement, from fmi3FunctionTypes.h: an FMU must export them all.

Usage: python3 generate_stubs.py fmi3FunctionTypes.h output.inc
"""

import re
import sys
from pathlib import Path

IMPLEMENTED = {
    "GetVersion",
    "SetDebugLogging",
    "InstantiateCoSimulation",
    "InstantiateModelExchange",
    "InstantiateScheduledExecution",
    "FreeInstance",
    "EnterInitializationMode",
    "ExitInitializationMode",
    "Terminate",
    "Reset",
    "GetFloat64",
    "SetFloat64",
    "GetFMUState",
    "SetFMUState",
    "FreeFMUState",
    "SerializedFMUStateSize",
    "SerializeFMUState",
    "DeserializeFMUState",
    "DoStep",
    "EnterStepMode",
}


def main() -> None:
    text = re.sub(r"/\*.*?\*/", "", Path(sys.argv[1]).read_text(encoding="utf-8"), flags=re.S)
    out = ["/* Generated by generate_stubs.py from fmi3FunctionTypes.h. */"]
    pattern = r"typedef\s+(\w+)\s+fmi3(\w+)TYPE\s*\((.*?)\)\s*;"
    for match in re.finditer(pattern, text, flags=re.S):
        result, name, args = match.group(1), match.group(2), " ".join(match.group(3).split())
        if name in IMPLEMENTED:
            continue
        if result != "fmi3Status":
            sys.exit(f"fmi3{name} returns {result}; add it to dc_drive.c")
        out.append(f"fmi3Status fmi3{name}({args}) {{")
        for param in (p.strip() for p in args.split(",")) if args else []:
            out.append(f"    (void){param.replace('[]', '').split()[-1].lstrip('*')};")
        out.append("    return fmi3Error;\n}\n")
    Path(sys.argv[2]).write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
